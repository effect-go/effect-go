// writeFiles writes files, by their paths in dir.
func writeFiles(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for name, src := range files {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o777); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(src), 0o666); err != nil {
			t.Fatal(err)
		}
	}
}

// module makes the current directory a new module with files.
func module(t *testing.T, files map[string]string) {
	t.Helper()
	dir := t.TempDir()
	writeFiles(t, dir, files)
	t.Chdir(dir)
}

// A fresh module, with no generated Go yet, whose packages import each
// other's .ego code, and an external test that imports a package importing
// its own: one ego generate is enough.
func TestGenerateConverges(t *testing.T) {
	if testing.Short() {
		t.Skip("runs go list")
	}
	module(t, map[string]string{
		"go.mod":   "module example.com/conv\n\ngo 1.26\n",
		"main.ego": "package main\n\nimport \"example.com/conv/b\"\n\nfunc main() { println(b.B()) }\n",
		"a/a.ego":  "package a\n\nfunc A() int { return 1 }\n",
		"b/b.ego":  "package b\n\nimport \"example.com/conv/a\"\n\nfunc B() int { return a.A() + 1 }\n",
		"a/a_test.ego": `package a_test

import (
	"testing"

	"example.com/conv/a"
	"example.com/conv/b"
)

func TestA(t *testing.T) {
	if b.B() != a.A()+1 {
		t.Fatal(b.B())
	}
}
`,
	})
	if err := generate([]string{"./..."}); err != nil {
		t.Fatalf("first run: %v", err)
	}
	if err := generate([]string{"-check", "./..."}); err != nil {
		t.Fatalf("a second run still had work: %v", err)
	}
}

// Deleting or renaming a .ego file removes the Go generated from it, and
// -check reports it until then. Hand-written *_ego.go files stay.
func TestGenerateRemovesLeftovers(t *testing.T) {
	if testing.Short() {
		t.Skip("runs go list")
	}
	module(t, map[string]string{
		"go.mod":        "module example.com/left\n\ngo 1.26\n",
		"a/a.ego":       "package a\n\nfunc A() int { return 1 }\n",
		"a/old.ego":     "package a\n\nfunc Old() int { return 2 }\n",
		"a/hand_ego.go": "package a\n\nfunc Hand() int { return 3 }\n",
		"gone/gone.ego": "package gone\n",
	})
	if err := generate([]string{"./..."}); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove("gone/gone.ego"); err != nil {
		t.Fatal(err)
	}
	if err := generate([]string{"-check", "./..."}); err == nil {
		t.Fatal("-check passed with a leftover")
	}
	if err := os.Rename("a/old.ego", "a/new.ego"); err != nil {
		t.Fatal(err)
	}
	if err := generate([]string{"./..."}); err != nil {
		t.Fatal(err)
	}
	// A rename that only changes case, which the file system may ignore.
	if err := os.Rename("a/new.ego", "a/New.ego"); err != nil {
		t.Fatal(err)
	}
	if err := generate([]string{"./..."}); err != nil {
		t.Fatal(err)
	}
	entries, _ := os.ReadDir("a")
	var names []string
	for _, e := range entries {
		names = append(names, e.Name())
	}
	for name, want := range map[string]bool{"old_ego.go": false, "new_ego.go": false, "New_ego.go": true, "hand_ego.go": true} {
		if slices.Contains(names, name) != want {
			t.Errorf("a/%s exists: %v, want %v", name, !want, want)
		}
	}
	if exists("gone/gone_ego.go") {
		t.Error("gone/gone_ego.go is left")
	}
}

// A generated file whose header a coverage run rewrote still names its
// source, by its own name; only layers_ego.go is the wiring's.
func TestGeneratedFrom(t *testing.T) {
	dir := t.TempDir()
	writeFiles(t, dir, map[string]string{
		"x_ego.go":      "// Code generated by ego generate. DO NOT EDIT.\n\npackage x\n",
		"y_ego_test.go": "// Code generated by ego generate from y_test.ego. DO NOT EDIT.\r\n\npackage x\n",
		"layers_ego.go": "// Code generated by ego generate. DO NOT EDIT.\n\npackage x\n",
		"hand.go":       "package x\n",
	})
	for name, want := range map[string]string{"x_ego.go": "x.ego", "y_ego_test.go": "y_test.ego", "layers_ego.go": "", "hand.go": "-"} {
		src, ok := generatedFrom(filepath.Join(dir, name))
		if !ok {
			src = "-"
		}
		if src != want {
			t.Errorf("generatedFrom(%s) = %q, want %q", name, src, want)
		}
	}
}

// ego generate doesn't overwrite a hand-written file named as the Go of a
// .ego file would be, nor the wiring's.
func TestGenerateKeepsHandWritten(t *testing.T) {
	if testing.Short() {
		t.Skip("runs go list")
	}
	hand, handC := "package a\n\nfunc Hand() int { return 3 }\n", "package c\n\nfunc Hand() int { return 3 }\n"
	module(t, map[string]string{
		"go.mod":          "module example.com/hand\n\ngo 1.26\n",
		"a/foo.ego":       "package a\n\nfunc Foo() int { return 1 }\n",
		"a/foo_ego.go":    hand,
		"b/layers.ego":    "package b\n",
		"b/inject.go":     "//go:build egolayers\n\npackage b\n",
		"c/c.ego":         "package c\n",
		"c/layers_ego.go": handC,
		"c/inject.go":     "//go:build egolayers\n\npackage c\n\nfunc F() {}\n",
		"d/d.ego":         "package d\n",
	})
	err := generate([]string{"./..."})
	if err == nil {
		t.Fatal("no error")
	}
	if got, _ := os.ReadFile("a/foo_ego.go"); string(got) != hand {
		t.Errorf("a/foo_ego.go was overwritten:\n%s", got)
	}
	if exists("b/layers_ego.go") {
		t.Error("b/layers.ego was generated over the wiring's file")
	}
	if got, _ := os.ReadFile("c/layers_ego.go"); string(got) != handC {
		t.Errorf("c/layers_ego.go was overwritten:\n%s", got)
	}
	if !exists("d/d_ego.go") {
		t.Error("the other packages were not generated")
	}
}

// Arguments name directories, .ego files and import paths, which must
// exist; ./... skips what go skips.
func TestGenerateArgs(t *testing.T) {
	if testing.Short() {
		t.Skip("runs go list")
	}
	module(t, map[string]string{
		"go.mod":      "module example.com/args\n\ngo 1.26\n",
		"a/a.ego":     "package a\n",
		"b/b.ego":     "package b\n",
		"_skip/s.ego": "package skip\n",
		"c/d/d.ego":   "package d\n",
	})
	for _, args := range [][]string{{"./typo"}, {"-check", "./typo"}, {"nope.ego"}, {"example.com/args/typo"}} {
		if err := generate(args); err == nil {
			t.Errorf("generate %q: no error", args)
		}
	}
	if err := generate([]string{"example.com/args/a", "example.com/args/c/..."}); err != nil {
		t.Fatal(err)
	}
	for path, want := range map[string]bool{"a/a_ego.go": true, "b/b_ego.go": false, "c/d/d_ego.go": true} {
		if exists(path) != want {
			t.Errorf("%s exists: %v, want %v", path, !want, want)
		}
	}
	if err := generate([]string{"./..."}); err != nil {
		t.Fatal(err)
	}
	if exists("_skip/s_ego.go") {
		t.Error("./... generated _skip")
	}
}

// Build constraints, in a .ego file's name or in its //go:build line, carry
// over to its Go. A file they exclude here is generated all the same, in a
// build context where they hold; one that no context includes isn't, but
// its Go mustn't build here either.
func TestGenerateConstraints(t *testing.T) {
	if testing.Short() {
		t.Skip("runs go list")
	}
	other := "linux"
	if runtime.GOOS == other {
		other = "darwin"
	}
	module(t, map[string]string{
		"go.mod":                       "module example.com/cons\n\ngo 1.26\n",
		"p/p_" + runtime.GOOS + ".ego": "package p\n\nfunc Platform() string { return \"here\" }\n",
		"p/p_" + other + ".ego":        "package p\n\nfunc Platform() string { return \"there\" }\n",
		"p/l.ego":                      "package p\n\nfunc L() int { return 1 }\n",
		"p/never.ego":                  "//go:build linux && windows\n\npackage p\n",
		"p/main_test.go":               "package p\n\nimport \"testing\"\n\nfunc TestP(t *testing.T) { _ = Platform() }\n",
	})
	if err := generate([]string{"./..."}); err != nil {
		t.Fatal(err)
	}
	for _, goos := range []string{runtime.GOOS, other} {
		code, _ := os.ReadFile("p/p_" + goos + "_ego.go")
		if !strings.Contains(string(code), "\n//go:build "+goos+"\n") {
			t.Errorf("p_%s_ego.go: no //go:build line:\n%s", goos, code)
		}
	}
	if exists("p/never_ego.go") {
		t.Error("a file no build context includes was generated")
	}
	if err := generate([]string{"-check", "./..."}); err != nil {
		t.Fatal(err)
	}

	// A constraint added to l.ego leaves l_ego.go stale, though l.ego isn't
	// compiled here anymore: ego generate compiles it with the tag.
	writeFiles(t, "p", map[string]string{"l.ego": "//go:build integration\n\npackage p\n\nfunc L() int { return 1 }\n"})
	if err := generate([]string{"-check", "./..."}); !errors.Is(err, errSilent) {
		t.Fatalf("stale l_ego.go: %v", err)
	}
	if err := generate([]string{"./..."}); err != nil {
		t.Fatal(err)
	}
	if l, _ := os.ReadFile("p/l_ego.go"); !strings.Contains(string(l), "\n//go:build integration\n") {
		t.Errorf("l_ego.go:\n%s", l)
	}
	if err := generate([]string{"-tags", "integration", "-check", "./..."}); err != nil {
		t.Fatal(err)
	}

	// The Go of a file no context includes is stale if it builds here.
	writeFiles(t, "p", map[string]string{"never_ego.go": "// Code generated by ego generate from never.ego. DO NOT EDIT.\n\npackage p\n"})
	if err := generate([]string{"./..."}); !errors.Is(err, errSilent) {
		t.Fatalf("stale never_ego.go: %v", err)
	}
}

// The advice for a module missing the runtime's requirements is go get,
// not go mod tidy, which can't see .ego imports.
func TestRuntimeHint(t *testing.T) {
	err := runtimeHint(errors.New("loading imports: go: updates to go.mod needed; to update it:\n\tgo mod tidy"))
	if !strings.Contains(err.Error(), "go get github.com/effect-go/effect-go/scope@") {
		t.Errorf("no advice: %v", err)
	}
	if err := runtimeHint(errors.New("other")); err.Error() != "other" {
		t.Errorf("changed: %v", err)
	}
}
