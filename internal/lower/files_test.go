// pkg writes a package's files to a new directory, with a go.mod unless
// files has one or is nil there, and returns the directory.
func pkg(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	if _, ok := files["go.mod"]; !ok {
		files["go.mod"] = "module example.com/p\n\ngo 1.26\n"
	}
	for name, src := range files {
		if name == "go.mod" && src == "" {
			continue
		}
		if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o666); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func generate(t *testing.T, dir string) *Result {
	t.Helper()
	res, err := Generate(Config{Dir: dir})
	if err != nil {
		t.Fatal(err)
	}
	return res
}

func diags(res *Result) string {
	var b strings.Builder
	for _, d := range res.Diags {
		b.WriteString(filepath.Base(d.Pos.String()) + ": " + d.Msg + "\n")
	}
	return b.String()
}

// A file ego generate wrote from a .ego file that is gone isn't part of the
// package, even before ego generate removes it: neither is one from a file
// renamed only in case.
func TestLeftover(t *testing.T) {
	dir := pkg(t, map[string]string{
		"New.ego":    "package p\n\nfunc A() int { return 1 }\n",
		"old_ego.go": "// Code generated by ego generate from old.ego. DO NOT EDIT.\n\npackage p\n\nfunc A() int { return 1 }\n",
		"new_ego.go": "// Code generated by ego generate from new.ego. DO NOT EDIT.\n\npackage p\n\nfunc A() int { return 1 }\n",
		"cov_ego.go": "// Code generated by ego generate. DO NOT EDIT.\n\npackage p\n\nfunc A() int { return 1 }\n",
		"hand.go":    "package p\n\nfunc B() int { return 2 }\n",
	})
	res := generate(t, dir)
	if len(res.Diags) > 0 {
		t.Fatalf("diagnostics:\n%s", diags(res))
	}
	var got []string
	for _, path := range res.Leftovers {
		got = append(got, filepath.Base(path))
	}
	if strings.Join(got, " ") != "cov_ego.go new_ego.go old_ego.go" {
		t.Errorf("leftovers: %v", got)
	}
}

// A hand-written file named as a .ego file's Go would be is reported, not
// overwritten.
func TestHandWritten(t *testing.T) {
	dir := pkg(t, map[string]string{
		"foo.ego":    "package p\n\nfunc Foo() int { return 1 }\n",
		"foo_ego.go": "package p\n\nfunc Hand() int { return 2 }\n",
	})
	res := generate(t, dir)
	if got := diags(res); got != "foo.ego:1:1: foo_ego.go: not generated by ego; rename it or foo.ego\n" || len(res.Outputs) > 0 {
		t.Errorf("got %d outputs, diagnostics:\n%s", len(res.Outputs), got)
	}
}

// A byte order mark doesn't end up in the middle of the generated file.
func TestBOM(t *testing.T) {
	dir := pkg(t, map[string]string{"a.ego": "\xef\xbb\xbfpackage p\n\nfunc A() int { return 1 }\n"})
	res := generate(t, dir)
	if len(res.Diags) > 0 || len(res.Outputs) != 1 {
		t.Fatalf("diagnostics:\n%s", diags(res))
	}
	if bytes.Contains(res.Outputs[0].Code, []byte("\xef\xbb\xbf")) {
		t.Errorf("BOM in\n%s", res.Outputs[0].Code)
	}
}

// Outside a module, each file gets the error, for the editor to show.
func TestOutsideModule(t *testing.T) {
	dir := pkg(t, map[string]string{"go.mod": "", "a.ego": "package p\n", "b.ego": "package p\n\nfunc B() {}\n"})
	res := generate(t, dir)
	if got := diags(res); strings.Count(got, "is not in a Go module") != 2 {
		t.Errorf("diagnostics:\n%s", got)
	}
}

// A declaration in a .go file that a .ego file declares again is reported
// at both.
func TestRedeclaredInGo(t *testing.T) {
	dir := pkg(t, map[string]string{"a.go": "package p\n\nfunc F() {}\n", "b.ego": "package p\n\nfunc F() {}\n"})
	res := generate(t, dir)
	if got := diags(res); got != "a.go:3:6: F redeclared in this block\nb.ego:3:6: \tother declaration of F\n" {
		t.Errorf("diagnostics:\n%s", got)
	}
}

// The _GOOS and _GOARCH suffixes of a .ego file's name constrain its Go, as
// they would a .go file: _ego, at the end of its name, hides them.
func TestNameConstraint(t *testing.T) {
	const head = "// Code generated by ego generate from x.ego. DO NOT EDIT.\n\n"
	for _, c := range []struct{ name, code, want string }{
		{"x.ego", "package p\n", "package p\n"},
		{"x_test.ego", "package p\n", "package p\n"},
		{"linux.ego", "package p\n", "package p\n"},
		{"x_linux.ego", "package p\n", "//go:build linux\n\npackage p\n"},
		{"x_linux_test.ego", "package p\n", "//go:build linux\n\npackage p\n"},
		{"x_linux_arm64.ego", "// Doc.\npackage p\n", "//go:build linux && arm64\n\n// Doc.\npackage p\n"},
		{"x_darwin_linux.ego", "package p\n", "//go:build linux\n\npackage p\n"},
		{"linux_amd64.ego", "package p\n", "//go:build amd64\n\npackage p\n"},
		{"x_wasm.ego", "// Copyright.\n\n//go:build js || wasip1\n\npackage p\n", "// Copyright.\n\n//go:build wasm && (js || wasip1)\n\npackage p\n"},
	} {
		if got := string(addNameConstraint([]byte(head+c.code), c.name)); got != head+c.want {
			t.Errorf("%s:\n%s\nwant\n%s", c.name, got, head+c.want)
		}
	}
}

// A .ego file that build constraints exclude here isn't compiled. Its Go
// is reported missing, or stale if it builds here all the same. GOFLAGS's
// tags count, as they do for go list.
func TestExcluded(t *testing.T) {
	dir := pkg(t, map[string]string{
		"a.ego": "package p\n",
		"x.ego": "//go:build integration\n\npackage p\n\nfunc X() {}\n",
	})
	res := generate(t, dir)
	if len(res.Excluded) != 1 || !res.Excluded[0].Missing || len(res.Outputs) != 1 {
		t.Fatalf("excluded: %+v, %d outputs", res.Excluded, len(res.Outputs))
	}
	// As generated before the constraint was added.
	stale := "// Code generated by ego generate from x.ego. DO NOT EDIT.\n\npackage p\n\nfunc X() {}\n"
	if err := os.WriteFile(filepath.Join(dir, "x_ego.go"), []byte(stale), 0o666); err != nil {
		t.Fatal(err)
	}
	if res := generate(t, dir); len(res.Excluded) != 1 || !res.Excluded[0].Stale {
		t.Fatalf("excluded: %+v", res.Excluded)
	}
	t.Setenv("GOFLAGS", "-mod=mod -tags=integration")
	res = generate(t, dir)
	if len(res.Excluded) != 0 || len(res.Outputs) != 2 || len(res.Diags) > 0 {
		t.Fatalf("with the tag: excluded %+v, %d outputs\n%s", res.Excluded, len(res.Outputs), diags(res))
	}
}
